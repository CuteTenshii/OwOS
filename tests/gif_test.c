/* ---- a small independent GIF writer ---- */

struct buf {
  unsigned char *p;
  int len, cap;
};

static void put(struct buf *b, int c)
{
  if (b->len == b->cap) {
    b->cap = b->cap ? b->cap * 2 : 256;
    b->p = realloc(b->p, (size_t)b->cap);
  }
  b->p[b->len++] = (unsigned char)c;
}

static void put16(struct buf *b, int v)
{
  put(b, v & 255);
  put(b, v >> 8);
}

/* LZW: dictionary keyed by (prefix << 8 | symbol); `clear_full` emits a clear code when the table fills,
 * otherwise the encoder keeps going with the full table (a deferred clear). */
static void lzw(struct buf *out, const unsigned char *px, int n, int mcs, int clear_full)
{
  static int keys[8192], vals[8192];
  int clear = 1 << mcs, eoi = clear + 1, next = eoi + 1, csize = mcs + 1;
  unsigned acc = 0;
  int nbits = 0;
  struct buf raw = {0, 0, 0};

#define EMIT(code)                                                                                                     \
  do {                                                                                                                 \
    acc |= (unsigned)(code) << nbits;                                                                                  \
    nbits += csize;                                                                                                    \
    while (nbits >= 8) {                                                                                               \
      put(&raw, (int)(acc & 255));                                                                                     \
      acc >>= 8;                                                                                                       \
      nbits -= 8;                                                                                                      \
    }                                                                                                                  \
  } while (0)

  memset(keys, -1, sizeof keys);
  EMIT(clear);
  int w = px[0];
  for (int i = 1; i < n; i++) {
    int key = w << 8 | px[i], slot = (key * 2654435761u >> 19) & 8191;
    while (keys[slot] != -1 && keys[slot] != key)
      slot = (slot + 1) & 8191;
    if (keys[slot] == key) {
      w = vals[slot];
      continue;
    }
    EMIT(w);
    if (next < 4096) {
      keys[slot] = key;
      vals[slot] = next;
      if (next == (1 << csize) && csize < 12)
        csize++;
      next++;
      if (next == 4096 && clear_full) {
        EMIT(clear);
        memset(keys, -1, sizeof keys);
        next = eoi + 1;
        csize = mcs + 1;
      }
    }
    w = px[i];
  }
  EMIT(w);
  EMIT(eoi);
  if (nbits)
    put(&raw, (int)(acc & 255));
#undef EMIT
  for (int i = 0; i < raw.len; i += 255) {
    int c = raw.len - i < 255 ? raw.len - i : 255;
    put(out, c);
    for (int k = 0; k < c; k++)
      put(out, raw.p[i + k]);
  }
  put(out, 0);
  free(raw.p);
}

static void header(struct buf *b, int w, int h, const unsigned char (*pal)[3], int npal_bits)
{
  b->p = 0;
  b->len = b->cap = 0;
  for (const char *s = "GIF89a"; *s; s++)
    put(b, *s);
  put16(b, w);
  put16(b, h);
  put(b, 0x80 | ((npal_bits - 1) << 4) | (npal_bits - 1));
  put(b, 0);
  put(b, 0);
  for (int i = 0; i < 1 << npal_bits; i++)
    for (int c = 0; c < 3; c++)
      put(b, pal[i][c]);
}

static void frame(struct buf *b, int x, int y, int w, int h, int flags, int mcs, const unsigned char *px, int n,
                  int clear_full)
{
  put(b, 0x2c);
  put16(b, x);
  put16(b, y);
  put16(b, w);
  put16(b, h);
  put(b, flags);
  put(b, mcs);
  lzw(b, px, n, mcs, clear_full);
}

static unsigned char (*make_palette(int n))[3]
{
  static unsigned char p[256][3];
  for (int i = 0; i < n; i++) {
    p[i][0] = (unsigned char)(i * 37 + 5);
    p[i][1] = (unsigned char)(i * 91 + 17);
    p[i][2] = (unsigned char)(255 - i * 53);
  }
  return p;
}

/* Decode a one-frame GIF and compare the canvas with `want` (RGBA). */
static void check_canvas(const struct buf *b, unsigned w, unsigned h, const unsigned char *want)
{
  struct gif *g;
  unsigned gw, gh;
  unsigned char *canvas = calloc(w * h, 4);
  expect_eq(gif_open(&g, b->p, b->len, &gw, &gh), GIF_OK);
  expect(gw == w && gh == h);
  expect_eq(gif_next(g, canvas, NULL), GIF_FRAME);
  expect(memcmp(canvas, want, w * h * 4) == 0);
  expect_eq(gif_next(g, canvas, NULL), GIF_END);
  gif_close(g);
  free(canvas);
}

static void want_pixels(unsigned char *want, const unsigned char *px, int n, const unsigned char (*pal)[3], int npal)
{
  for (int i = 0; i < n; i++) {
    if (px[i] < npal) {
      memcpy(want + i * 4, pal[px[i]], 3);
      want[i * 4 + 3] = 255;
    }
  }
}

static void lzw_roundtrip(int mcs, int w, int h, int runs, int clear_full)
{
  struct buf b;
  int n = w * h, npal = 1 << mcs;
  unsigned char *px = malloc((unsigned)n), *want = calloc((unsigned)n, 4);
  unsigned seed = 12345u + (unsigned)mcs;
  unsigned char (*pal)[3] = make_palette(npal > 256 ? 256 : npal);

  for (int i = 0; i < n; i++) {
    seed = seed * 1103515245u + 12345u;
    px[i] = runs ? (unsigned char)((i / 7) % npal) : (unsigned char)((seed >> 16) % npal);
  }
  header(&b, w, h, (const unsigned char (*)[3])pal, mcs < 1 ? 1 : mcs);
  frame(&b, 0, 0, w, h, 0, mcs, px, n, clear_full);
  put(&b, 0x3b);
  want_pixels(want, px, n, (const unsigned char (*)[3])pal, npal);
  check_canvas(&b, (unsigned)w, (unsigned)h, want);
  free(b.p);
  free(px);
  free(want);
}

static void lzw_every_min_code_size(void)
{
  for (int mcs = 2; mcs <= 8; mcs++)
    lzw_roundtrip(mcs, 37, 23, 0, 1);
}

static void lzw_min_code_size_one(void) { lzw_roundtrip(1, 13, 9, 0, 1); }
static void lzw_repeated_runs(void) { lzw_roundtrip(2, 30, 20, 1, 1); }
static void lzw_table_full_with_clear(void) { lzw_roundtrip(3, 96, 80, 0, 1); }
static void lzw_table_full_deferred_clear(void) { lzw_roundtrip(3, 96, 80, 0, 0); }
static void lzw_eight_bit_full_table(void) { lzw_roundtrip(8, 150, 110, 0, 0); }

static void interlaced_sub_rect_with_local_palette(void)
{
  enum { SW = 16, SH = 13, FX = 3, FY = 2, FW = 7, FH = 11 };
  struct buf b;
  unsigned char px[FW * FH], stream[FW * FH], want[SW * SH * 4] = {0};
  unsigned char (*pal)[3] = make_palette(8);
  unsigned char lp[8][3];
  static const int start[4] = {0, 4, 2, 1}, step[4] = {8, 8, 4, 2};
  int k = 0;

  memcpy(lp, pal, sizeof lp);
  for (int i = 0; i < FW * FH; i++)
    px[i] = (unsigned char)((i * 5 + i / 3) % 8);
  for (int p = 0; p < 4; p++)
    for (int r = start[p]; r < FH; r += step[p]) {
      memcpy(stream + k, px + r * FW, FW);
      k += FW;
    }
  header(&b, SW, SH, (const unsigned char (*)[3])pal, 2);
  put(&b, 0x21); /* graphic control: transparent index 3 */
  put(&b, 0xf9);
  put(&b, 4);
  put(&b, 1);
  put16(&b, 5);
  put(&b, 3);
  put(&b, 0);
  put(&b, 0x2c);
  put16(&b, FX);
  put16(&b, FY);
  put16(&b, FW);
  put16(&b, FH);
  put(&b, 0x40 | 0x80 | 2);
  for (int i = 0; i < 8; i++)
    for (int c = 0; c < 3; c++)
      put(&b, lp[i][c]);
  put(&b, 3);
  lzw(&b, stream, FW * FH, 3, 1);
  put(&b, 0x3b);
  for (int y = 0; y < FH; y++)
    for (int x = 0; x < FW; x++) {
      unsigned char *p = want + ((FY + y) * SW + FX + x) * 4;
      if (px[y * FW + x] == 3)
        continue;
      memcpy(p, lp[px[y * FW + x]], 3);
      p[3] = 255;
    }
  check_canvas(&b, SW, SH, want);
  free(b.p);
}

static void short_pixel_data_leaves_the_rest_untouched(void)
{
  struct buf b;
  unsigned char px[20], want[10 * 10 * 4] = {0};
  unsigned char (*pal)[3] = make_palette(4);

  for (int i = 0; i < 20; i++)
    px[i] = (unsigned char)((i * 3 + 1) % 4);
  header(&b, 10, 10, (const unsigned char (*)[3])pal, 2);
  frame(&b, 0, 0, 10, 10, 0, 2, px, 20, 1);
  put(&b, 0x3b);
  want_pixels(want, px, 20, (const unsigned char (*)[3])pal, 4);
  check_canvas(&b, 10, 10, want);
  free(b.p);
}

static void surplus_pixel_data_is_ignored(void)
{
  struct buf b;
  unsigned char px[6 * 4 + 50], want[6 * 4 * 4] = {0};
  unsigned char (*pal)[3] = make_palette(4);

  for (int i = 0; i < (int)sizeof px; i++)
    px[i] = (unsigned char)((i * 7 + 2) % 4);
  header(&b, 6, 4, (const unsigned char (*)[3])pal, 2);
  frame(&b, 0, 0, 6, 4, 0, 2, px, (int)sizeof px, 1);
  put(&b, 0x3b);
  want_pixels(want, px, 24, (const unsigned char (*)[3])pal, 4);
  check_canvas(&b, 6, 4, want);
  free(b.p);
}

static void loop_extension_counts(void)
{
  struct buf b;
  struct gif *g;
  unsigned w, h;
  unsigned char px[4] = {0, 1, 2, 3};
  unsigned char (*pal)[3] = make_palette(4);
  static const unsigned char counts[] = {0, 1, 7};
  static const int plays[] = {0, 2, 8};

  for (int i = 0; i < 3; i++) {
    header(&b, 2, 2, (const unsigned char (*)[3])pal, 2);
    put(&b, 0x21);
    put(&b, 0xff);
    put(&b, 11);
    for (const char *s = "NETSCAPE2.0"; *s; s++)
      put(&b, *s);
    put(&b, 3);
    put(&b, 1);
    put16(&b, counts[i]);
    put(&b, 0);
    frame(&b, 0, 0, 2, 2, 0, 2, px, 4, 1);
    put(&b, 0x3b);
    expect_eq(gif_open(&g, b.p, b.len, &w, &h), GIF_OK);
    expect_eq(gif_loops(g), plays[i]);
    gif_close(g);
    free(b.p);
  }
}

