static void rejects_bad_headers(void)
{
  struct gif *g = (struct gif *)1;
  unsigned w, h;
  unsigned char d[32] = "GIF89a";

  expect_eq(gif_open(&g, (const unsigned char *)"GIF89", 5, &w, &h), GIF_EBADSIG);
  expect(g == NULL);
  expect_eq(gif_open(&g, (const unsigned char *)"PNG89a000000000000", 18, &w, &h), GIF_EBADSIG);
  expect_eq(gif_open(&g, d, 9, &w, &h), GIF_ETRUNC);
  expect_eq(gif_open(&g, d, 13, &w, &h), GIF_EFORMAT); /* 0x0 screen */
  d[6] = d[8] = 0x01;
  d[7] = d[9] = 0x41; /* 16641 */
  expect_eq(gif_open(&g, d, 13, &w, &h), GIF_EFORMAT);
  d[6] = d[8] = 0x01;
  d[7] = d[9] = 0;
  d[10] = 0x80 | 7; /* 256-colour table promised but absent */
  expect_eq(gif_open(&g, d, 13, &w, &h), GIF_ETRUNC);
}

static void stream_without_frames(void)
{
  struct gif *g;
  unsigned w, h;
  unsigned char canvas[4];
  unsigned char d[] = "GIF89a\1\0\1\0\0\0\0\x3b";

  expect_eq(gif_open(&g, d, 14, &w, &h), GIF_OK);
  expect_eq(gif_next(g, canvas, NULL), GIF_EFORMAT);
  expect_eq(gif_next(g, canvas, NULL), GIF_END);
  gif_close(g);
  expect_eq(gif_open(&g, d, 13, &w, &h), GIF_OK); /* no trailer either */
  expect_eq(gif_next(g, canvas, NULL), GIF_ETRUNC);
  gif_close(g);
}

static void truncated_stream_keeps_decoded_frames(void)
{
  const struct fixture *f = &fixtures[FIX_dispose_previous];
  struct gif *g;
  unsigned w, h;
  int d, frames = 0, rc;
  unsigned char *canvas;

  expect_eq(gif_open(&g, f->data, f->len - 40, &w, &h), GIF_OK);
  canvas = calloc(w * h, 4);
  while ((rc = gif_next(g, canvas, &d)) == GIF_FRAME)
    frames++;
  expect_eq(rc, GIF_END);
  expect(frames >= 3 && frames <= 4);
  free(canvas);
  gif_close(g);
}

static void garbage_after_a_frame_is_an_error(void)
{
  struct buf b;
  struct gif *g;
  unsigned w, h;
  unsigned char px[4] = {0, 1, 2, 3}, canvas[2 * 2 * 4];
  unsigned char (*pal)[3] = make_palette(4);

  header(&b, 2, 2, (const unsigned char (*)[3])pal, 2);
  frame(&b, 0, 0, 2, 2, 0, 2, px, 4, 1);
  put(&b, 0x55);
  expect_eq(gif_open(&g, b.p, b.len, &w, &h), GIF_OK);
  expect_eq(gif_next(g, canvas, NULL), GIF_FRAME);
  expect_eq(gif_next(g, canvas, NULL), GIF_EFORMAT);
  expect_eq(gif_next(g, canvas, NULL), GIF_END);
  gif_close(g);
  free(b.p);
}

static void corrupt_and_truncated_streams_do_not_crash(void)
{
  for (const struct fixture *f = fixtures; f < fixtures + sizeof fixtures / sizeof *fixtures; f++) {
    unsigned char *bad = malloc((unsigned)f->len);
    for (int i = 0; i <= f->len; i++) {
      for (int mode = 0; mode < 2; mode++) {
        struct gif *g;
        unsigned w, h;
        int len = f->len, rc, frames = 0;
        unsigned char *canvas;

        memcpy(bad, f->data, (unsigned)f->len);
        if (mode == 0)
          len = i;
        else if (i < f->len)
          bad[i] ^= 0x55;
        else
          continue;
        if (gif_open(&g, bad, len, &w, &h) != GIF_OK)
          continue;
        canvas = calloc(w * h, 4);
        while ((rc = gif_next(g, canvas, NULL)) == GIF_FRAME && frames < 100)
          frames++;
        expect(rc <= GIF_END);
        gif_rewind(g, canvas);
        gif_next(g, canvas, NULL);
        free(canvas);
        gif_close(g);
      }
    }
    free(bad);
  }
}

