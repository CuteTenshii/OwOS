struct fixture {
  const char *name;
  const unsigned char *data;
  int len;
  unsigned w, h;
  uint32_t crc;
  int alpha;
};

#define FIXTURE(sym, w, h, crc, alpha) {#sym, sym, (int)sizeof sym, w, h, crc, alpha}

static const struct fixture fixtures[] = {
    FIXTURE(lossy_segments, 37, 21, 0x40d07a01u, 0),
    FIXTURE(lossy_4_partitions, 48, 32, 0xd0925fd8u, 0),
    FIXTURE(lossy_alpha_lossless, 32, 21, 0xe51fc0e6u, 1),
    FIXTURE(lossy_alpha_raw, 28, 20, 0xcc3c4604u, 1),
};

static uint32_t rgba_crc(const unsigned char *rgba, unsigned w, unsigned h) { return crc32(0, rgba, w * h * 4); }

static void check_fixture(const struct fixture *f)
{
  struct webp_info info;
  unsigned char *rgba;
  unsigned w, h;

  expect_eq(webp_probe(f->data, f->len, &info), WEBP_OK);
  expect_eq(info.lossless, 0);
  expect_eq(info.has_alpha, f->alpha);
  expect_eq(webp_decode(f->data, f->len, &rgba, &w, &h), WEBP_OK);
  expect_eq(w, f->w);
  expect_eq(h, f->h);
  expect(rgba && rgba_crc(rgba, w, h) == f->crc);
  free(rgba);
}

static void lossy_segments_matches_dwebp(void) { check_fixture(&fixtures[0]); }
static void lossy_four_partitions_match_dwebp(void) { check_fixture(&fixtures[1]); }
static void lossy_with_lossless_alpha_matches_dwebp(void) { check_fixture(&fixtures[2]); }
static void lossy_with_raw_alpha_matches_dwebp(void) { check_fixture(&fixtures[3]); }

static void lossy_without_alph_is_opaque(void)
{
  unsigned char *rgba;
  unsigned w, h;

  expect_eq(webp_decode(lossy_segments, sizeof lossy_segments, &rgba, &w, &h), WEBP_OK);
  for (unsigned i = 0; i < w * h; i++)
    if (rgba[i * 4 + 3] != 255) {
      expect(0);
      break;
    }
  free(rgba);
}

/* Forward ALPH prediction filter, independent of the decoder's inverse. */
static void alpha_filter(const unsigned char *a, unsigned char *out, int w, int h, int method)
{
  for (int y = 0; y < h; y++)
    for (int x = 0; x < w; x++) {
      int pred;
      if (!x && !y)
        pred = 0;
      else if (!y)
        pred = a[x - 1];
      else if (!x)
        pred = a[(y - 1) * w];
      else if (method == 1)
        pred = a[y * w + x - 1];
      else if (method == 2)
        pred = a[(y - 1) * w + x];
      else {
        pred = a[y * w + x - 1] + a[(y - 1) * w + x] - a[(y - 1) * w + x - 1];
        pred = pred < 0 ? 0 : pred > 255 ? 255 : pred;
      }
      out[y * w + x] = (unsigned char)(a[y * w + x] - pred);
    }
}

/* lossy_alpha_raw carries an unfiltered 28x20 plane: refilter it with each method and patch the chunk. */
static void alph_prediction_filters(void)
{
  unsigned char *orig, *patched, *plane, *res;
  unsigned w, h, n = 28 * 20;
  int len = (int)sizeof lossy_alpha_raw, off = -1;

  expect_eq(webp_decode(lossy_alpha_raw, len, &orig, &w, &h), WEBP_OK);
  for (int i = 12; i + 8 <= len; i++)
    if (!memcmp(lossy_alpha_raw + i, "ALPH", 4)) {
      off = i + 8;
      break;
    }
  expect(off > 0 && lossy_alpha_raw[off] == 0);
  plane = malloc(n);
  res = malloc(n);
  patched = malloc((unsigned)len);
  for (unsigned i = 0; i < n; i++)
    plane[i] = orig[i * 4 + 3];
  for (int method = 1; method <= 3; method++) {
    unsigned char *again;
    alpha_filter(plane, res, 28, 20, method);
    memcpy(patched, lossy_alpha_raw, (unsigned)len);
    patched[off] = (unsigned char)(method << 2);
    memcpy(patched + off + 1, res, n);
    expect_eq(webp_decode(patched, len, &again, &w, &h), WEBP_OK);
    expect(again && memcmp(again, orig, n * 4) == 0);
    free(again);
  }
  free(plane);
  free(res);
  free(patched);
  free(orig);
}

static void lossless_round_trip(void)
{
  unsigned char src[16 * 12 * 4], *enc, *dec;
  unsigned w, h;
  int enc_len;

  for (int i = 0; i < 16 * 12; i++) {
    src[i * 4 + 0] = (unsigned char)(i * 5);
    src[i * 4 + 1] = (unsigned char)(i / 16 * 20);
    src[i * 4 + 2] = (unsigned char)(i * i);
    src[i * 4 + 3] = (unsigned char)(255 - i);
  }
  expect_eq(webp_encode(src, 16, 12, &enc, &enc_len), WEBP_OK);
  expect_eq(webp_decode(enc, enc_len, &dec, &w, &h), WEBP_OK);
  expect(w == 16 && h == 12 && memcmp(src, dec, sizeof src) == 0);
  free(enc);
  free(dec);
}

static void rejects_bad_containers(void)
{
  unsigned char bad[sizeof lossy_segments], *rgba;
  unsigned w, h;

  memcpy(bad, lossy_segments, sizeof bad);
  bad[0] = 'X';
  expect_eq(webp_decode(bad, (int)sizeof bad, &rgba, &w, &h), WEBP_EBADSIG);
  expect(rgba == NULL);
  memcpy(bad, lossy_segments, sizeof bad);
  bad[23] ^= 0xff; /* VP8 start code */
  expect_eq(webp_decode(bad, (int)sizeof bad, &rgba, &w, &h), WEBP_EFORMAT);
  expect(rgba == NULL);
}

static void corrupt_and_truncated_lossy_streams_do_not_crash(void)
{
  unsigned char *rgba;
  unsigned w, h;

  for (const struct fixture *f = fixtures; f < fixtures + sizeof fixtures / sizeof *fixtures; f++) {
    unsigned char *bad = malloc((unsigned)f->len);
    for (int i = 12; i < f->len; i++) {
      memcpy(bad, f->data, (unsigned)f->len);
      bad[i] ^= 0x55;
      if (webp_decode(bad, f->len, &rgba, &w, &h) == WEBP_OK)
        free(rgba);
    }
    for (int i = 0; i < f->len; i++)
      if (webp_decode(f->data, i, &rgba, &w, &h) == WEBP_OK)
        free(rgba);
    free(bad);
  }
}

int OWOS_TEST_ENTRY(void)
{
  test("lossy: segments and 4x4 modes match dwebp", lossy_segments_matches_dwebp);
  test("lossy: four token partitions match dwebp", lossy_four_partitions_match_dwebp);
  test("lossy: lossless ALPH matches dwebp", lossy_with_lossless_alpha_matches_dwebp);
  test("lossy: raw ALPH matches dwebp", lossy_with_raw_alpha_matches_dwebp);
  test("lossy without ALPH is opaque", lossy_without_alph_is_opaque);
  test("ALPH prediction filters", alph_prediction_filters);
  test("lossless round trip", lossless_round_trip);
  test("rejects bad containers", rejects_bad_containers);
  test("corrupt and truncated lossy streams fail without crashing", corrupt_and_truncated_lossy_streams_do_not_crash);
  return 0;
}
