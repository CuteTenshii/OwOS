#define RED 0xff0000ffu
#define BLUE 0xffff0000u /* little-endian R,G,B,A bytes */

static unsigned first_pixel(const struct imganim *a)
{
  unsigned p;
  memcpy(&p, a->rgba, 4);
  return p;
}

/* Step until playback ends, recording each frame's first pixel and delay; returns the frame count. */
static int play(struct imganim *a, unsigned *px, unsigned *delay, int max)
{
  int n = 0;
  while (n < max && imganim_step(a, &delay[n])) {
    px[n] = first_pixel(a);
    n++;
  }
  return n;
}

static void still_gif_plays_one_frame(void)
{
  struct imganim *a = imganim_open(gif_still, sizeof gif_still);
  unsigned px[4], delay[4];

  expect(a != NULL);
  expect_eq(a->w, 2);
  expect_eq(a->h, 2);
  expect_eq(play(a, px, delay, 4), 1);
  expect_eq(px[0], RED);
  expect_eq(delay[0], 100); /* a zero delay is clamped to 100 ms */
  imganim_close(a);
}

static void gif_without_loop_extension_plays_once(void)
{
  struct imganim *a = imganim_open(gif_once, sizeof gif_once);
  unsigned px[8], delay[8];

  expect_eq(play(a, px, delay, 8), 2);
  expect_eq(px[0], RED);
  expect_eq(px[1], BLUE);
  expect_eq(delay[0], 200);
  expect_eq(delay[1], 300);
  imganim_close(a);
}

static void gif_loop_count_is_honoured(void)
{
  struct imganim *a = imganim_open(gif_twice, sizeof gif_twice);
  unsigned px[16], delay[16];

  /* NETSCAPE count 2 repeats twice after the first play: three plays of two frames */
  expect_eq(play(a, px, delay, 16), 6);
  for (int i = 0; i < 6; i++)
    expect_eq(px[i], i & 1 ? BLUE : RED);
  expect_eq(delay[1], 500);
  imganim_close(a);
}

static void infinite_gif_keeps_looping(void)
{
  struct imganim *a = imganim_open(gif_forever, sizeof gif_forever);
  unsigned px[40], delay[40];

  expect_eq(play(a, px, delay, 40), 40);
  for (int i = 0; i < 40; i++) {
    expect_eq(px[i], i & 1 ? BLUE : RED);
    expect_eq(delay[i], i & 1 ? 70 : 50);
  }
  imganim_close(a);
}

static void animated_webp_plays_its_loop_count(void)
{
  struct imganim *a;
  unsigned px[16], delay[16];

  expect_eq(imganim_sniff(webp_anim, sizeof webp_anim), IMGANIM_WEBP);
  a = imganim_open(webp_anim, sizeof webp_anim);
  expect(a != NULL);
  expect_eq(a->w, 8);
  expect_eq(a->h, 8);
  expect_eq(play(a, px, delay, 16), 6);
  for (int i = 0; i < 6; i++) {
    expect_eq(px[i], i & 1 ? BLUE : RED);
    expect_eq(delay[i], i & 1 ? 70 : 40);
  }
  imganim_close(a);
}

static void sniff_and_open_reject_other_data(void)
{
  static const unsigned char png[] = {0x89, 'P', 'N', 'G', 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0};
  unsigned char bad[10];

  expect_eq(imganim_sniff(gif_still, sizeof gif_still), IMGANIM_GIF);
  expect_eq(imganim_sniff(png, sizeof png), IMGANIM_NONE);
  expect(imganim_open(png, sizeof png) == NULL);
  expect(imganim_open(gif_still, 5) == NULL);
  memcpy(bad, gif_still, sizeof bad);
  bad[4] = '5'; /* GIF85a */
  expect_eq(imganim_sniff(bad, sizeof bad), IMGANIM_NONE);
}

int OWOS_TEST_ENTRY(void)
{
  test("a still GIF plays one frame", still_gif_plays_one_frame);
  test("a GIF without NETSCAPE plays once", gif_without_loop_extension_plays_once);
  test("GIF loop count is honoured", gif_loop_count_is_honoured);
  test("a loop-forever GIF keeps looping", infinite_gif_keeps_looping);
  test("an animated WebP plays its loop count", animated_webp_plays_its_loop_count);
  test("sniff and open reject other data", sniff_and_open_reject_other_data);
  return 0;
}
