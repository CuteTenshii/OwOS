static const char cyrillic_text[] =
    "программа сжатия κείμενο Ελληνικά загрузка память это браузер текст данных тест память Ελληνικά страница Привет "
    "память κείμενο текст браузер текст мир сжатия Ελληνικά сжатия загрузка Привет это браузер данных κείμενο тест "
    "текст браузер Ελληνικά страница";

static void check_utf8_context(void)
{
  int len = 0;
  unsigned char *out = brotli_decompress(cyrillic_br, (int)sizeof cyrillic_br, &len);
  expect(out != 0);
  expect(len == (int)strlen(cyrillic_text));
  expect(out && memcmp(out, cyrillic_text, (size_t)len) == 0);
  free(out);
}

static void check_corrupt_streams(void)
{
  int len = 0;
  unsigned char bad[sizeof cyrillic_br];
  size_t i;
  for (i = 0; i < sizeof cyrillic_br; i++) {
    memcpy(bad, cyrillic_br, sizeof bad);
    bad[i] ^= 0x55;
    free(brotli_decompress(bad, (int)sizeof bad, &len));
  }
  for (i = 0; i < sizeof cyrillic_br; i++)
    free(brotli_decompress(cyrillic_br, (int)i, &len));
}

int main(void)
{
  test("UTF-8 context lookup for two-byte lead bytes", check_utf8_context);
  test("corrupt and truncated streams fail without crashing", check_corrupt_streams);
  return 0;
}
