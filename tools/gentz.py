def footer(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"TZif" or data[4:5] < b"2":
        sys.exit("%s: not TZif v2+" % path)
    lines = data.rstrip(b"\n").rsplit(b"\n", 1)
    return lines[-1].decode("ascii")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    names = sorted(set(ZONES))
    print("/* Generated by tools/gentz.py from TZif footers. Do not edit. */")
    print("static const struct tz_zone tz_zones[] = {")
    for name in names:
        rule = footer(os.path.join(root, name))
        if not rule:
            sys.exit("%s: empty footer" % name)
        print('\t{"%s", "%s"},' % (name, rule))
    print("};")


main()
