/* sysfs.h - a Linux-sysfs-style /sys hierarchy (see sysfs.c).
 *
 * Where /proc (procfs.h) is a flat set of read-only process/system info files,
 * /sys is a real multi-level tree of *devices and tunables*: class/input,
 * class/net, class/block, power, firmware. Attribute files are generated on
 * read and (when writable) perform a kernel action on write. fs.c routes /sys
 * paths here for ls/stat/read; syscall.c routes writes.
 *
 * `sub` is always the part after "/sys" ("" for /sys itself, "/class/input" for
 * a directory, "/class/input/mouse0/speed" for an attribute file).
 */
#ifndef OWOS_SYSFS_H
#define OWOS_SYSFS_H

/* Part of an absolute path after a leading "/sys", or NULL if not under /sys.
 * "/sys" -> "", "/sys/class" -> "/class". */
const char *sysfs_subpath(const char *path);

/* 1 = directory, 0 = attribute file, -1 = no such path. */
int sysfs_kind(const char *sub);

/* Generate an attribute file's text into buf; returns the byte count, or -1 if
 * `sub` is not a readable file. */
int sysfs_read(const char *sub, char *buf, int max);

/* Perform the control action behind a writable attribute; returns len on
 * success, -1 if the path isn't a writable file. */
int sysfs_write(const char *sub, const char *buf, int len);

/* 1 if `sub` is a writable attribute file. */
int sysfs_writable(const char *sub);

/* Generated byte length of an attribute file (0 for a directory). */
int sysfs_size(const char *sub);

/* Enumerate the children of the directory at `dirsub`: fill `name` with the
 * idx-th child and set *is_dir. Returns 1 if it exists, 0 past the end. */
int sysfs_enum(const char *dirsub, int idx, char *name, int max, int *is_dir);

#endif /* OWOS_SYSFS_H */
