/* procfs.h — read-only /proc generated on read (see procfs.c). */
#ifndef OWOS_PROCFS_H
#define OWOS_PROCFS_H

/* `procfs_subpath` returns the part of an absolute path after "/proc" (e.g.
 * "/cpuinfo"), or NULL if the path isn't under /proc. `procfs_read` fills buf
 * with the named file's generated text and returns the byte count, or -1 for an
 * unknown entry. fs_read routes /proc paths here. */
const char *procfs_subpath(const char *path);
int procfs_read(const char *sub, char *buf, int max);
/* The write side: a control node (e.g. /proc/power, /proc/net) performs a
 * kernel action from a writefile(); returns len on success, -1 if not writable.
 */
int procfs_write(const char *sub, const char *buf, int len);
int procfs_list(int idx, char *name, int max); /* enumerate /proc      */
int procfs_kind(const char *sub);              /* 1 dir / 0 file / -1 unknown       */
int procfs_size(const char *sub);              /* generated byte length of a file   */

/* Upper bound on one generated /proc or /sys file; the journal alone holds 16 KiB. */
#define PSEUDO_FILE_MAX 32768

#endif /* OWOS_PROCFS_H */
