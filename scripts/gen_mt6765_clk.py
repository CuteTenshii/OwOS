#!/usr/bin/env python3
"""Generate kernel/arch/aarch64/mt6765_clk.h from Linux's drivers/clk/mediatek/clk-mt6765.c.

usage: gen_mt6765_clk.py clk-mt6765.c > kernel/arch/aarch64/mt6765_clk.h
"""
import re
import sys

src = open(sys.argv[1]).read()

defs = dict(re.findall(r"#define\s+(CLK_CFG\w*)\s+(0x[0-9a-fA-F]+)", src))

ifr_regs = {}
for m in re.finditer(r"static const struct mtk_gate_regs (ifr\d)_cg_regs = \{(.*?)\};", src, re.S):
    f = dict(re.findall(r"\.(\w+)_ofs = (0x[0-9a-fA-F]+)", m.group(2)))
    ifr_regs[m.group(1)[3:]] = (f["set"], f["clr"], f["sta"])

gates = re.findall(r'GATE_IFR(\d)\((CLK_IFR_\w+),\s*"[^"]*",\s*"[^"]*",\s*(\d+)\)', src)

mux_block = re.search(r"static const struct mtk_mux top_muxes\[\] = \{(.*?)\n\};", src, re.S).group(1)
muxes = []
for m in re.finditer(r"MUX_GATE_CLR_SET_UPD(?:_FLAGS)?\((CLK_TOP_\w+),\s*\"[^\"]*\",\s*\w+,(.*?)\),\s*(?=/\*|MUX_|\Z)", mux_block, re.S):
    args = [a.strip() for a in m.group(2).replace("\n", " ").split(",")]
    args = [defs.get(a, a) for a in args]
    mux_ofs, set_ofs, clr_ofs, shift, width, gate, upd_ofs, upd = args[:8]
    muxes.append((m.group(1), mux_ofs, set_ofs, clr_ofs, shift, width, gate, upd))

if not gates or not muxes:
    sys.exit("nothing parsed")

out = ["/* mt6765_clk.h: MT6765 clock gate and mux tables.",
       " * Generated by scripts/gen_mt6765_clk.py from Linux drivers/clk/mediatek/clk-mt6765.c; do not edit. */",
       "#ifndef OWOS_ARCH_AARCH64_MT6765_CLK_H", "#define OWOS_ARCH_AARCH64_MT6765_CLK_H", "",
       "#include <stdint.h>", ""]
out.append("/* Infracfg gates: setting the SET bit gates the clock, the CLR bit ungates it, STA reads 1 while gated. */")
out.append("enum clk_ifr {")
out += [f"  {g[1]}," for g in gates]
out.append("  CLK_IFR_COUNT,\n};\n")
out.append("struct clk_gate_def {\n  uint16_t set, clr, sta;\n  uint8_t bit;\n};\n")
out.append("static const struct clk_gate_def clk_ifr_gates[CLK_IFR_COUNT] = {")
for n, name, bit in gates:
    s, c, t = ifr_regs[n]
    out.append(f"  [{name}] = {{{s}, {c}, {t}, {bit}}},")
out.append("};\n")
out.append("/* Topckgen muxes with a gate bit (-1: none) and an update bit in CLK_CFG_UPDATE (-1: none). */")
out.append("enum clk_top_mux {")
out += [f"  {m[0]}," for m in muxes]
out.append("  CLK_TOP_MUX_COUNT,\n};\n")
out.append("struct clk_mux_def {\n  uint16_t cfg, set, clr;\n  uint8_t shift, width;\n  int8_t gate, upd;\n};\n")
out.append("static const struct clk_mux_def clk_top_muxes[CLK_TOP_MUX_COUNT] = {")
for name, mo, so, co, sh, wd, ga, up in muxes:
    out.append(f"  [{name}] = {{{mo}, {so}, {co}, {sh}, {wd}, {ga}, {up}}},")
out.append("};\n")
out.append(f"#define CLK_CFG_UPDATE {defs['CLK_CFG_UPDATE']}\n")
out.append("#endif")
print("\n".join(out))
